#!/usr/bin/env python3
"""
Direct AXI BRAM Controller Interface (ZedBoard PL Block RAM)
AI-Enabled Smart Waste Segregation & Monitoring System

Memory Map:
  Base Address: 0x40000000 (Configured in zedboard_block_design.tcl)
  Size:         256 KB (0x40000)

Usage:
  This module provides zero-copy, direct memory-mapped access to the
  PL Block RAM generated by the Vivado Block Memory Generator.
  Used to stage telemetry packets, sensor readings, and hardware triggers.
"""

import os
import struct
import mmap
from typing import Tuple, Dict

AXI_BRAM_BASE = 0x40000000
AXI_BRAM_SIZE = 256 * 1024  # 256 KB


class DirectBRAMInterface:
    """Interface to physical AXI BRAM mapped in PL fabric"""

    def __init__(self, base_addr: int = AXI_BRAM_BASE, size: int = AXI_BRAM_SIZE):
        self.base_addr = base_addr
        self.size = size
        self.fd = None
        self.mem = None
        self.is_hardware_active = False
        self._init_mmap()

    def _init_mmap(self):
        """Map physical address space into process memory via /dev/mem"""
        if os.path.exists("/dev/mem") and os.geteuid() == 0:
            try:
                self.fd = os.open("/dev/mem", os.O_RDWR | os.O_SYNC)
                self.mem = mmap.mmap(
                    self.fd,
                    self.size,
                    mmap.MAP_SHARED,
                    mmap.PROT_READ | mmap.PROT_WRITE,
                    offset=self.base_addr,
                )
                self.is_hardware_active = True
            except Exception as e:
                # Fallback to software buffer if not root or on host machine
                self.is_hardware_active = False
                self.mem = bytearray(self.size)
        else:
            self.is_hardware_active = False
            self.mem = bytearray(self.size)

    def write_sensor_snapshot(
        self,
        bin_fill_pct: float,
        temperature_c: float,
        humidity_pct: float,
        gas_adc: int,
        moisture_adc: int,
        alert_flag: int,
    ):
        """
        Write packed 32-byte telemetry record directly into BRAM offset 0x00:
          - Offset 0x00: Magic (0xDEADBEEF) [uint32]
          - Offset 0x04: Timestamp (Unix)   [float32]
          - Offset 0x08: Bin Fill Pct       [float32]
          - Offset 0x0C: Temperature C      [float32]
          - Offset 0x10: Humidity Pct       [float32]
          - Offset 0x14: Gas ADC            [uint32]
          - Offset 0x18: Moisture ADC       [uint32]
          - Offset 0x1C: Alert Flag         [uint32]
        """
        import time
        magic = 0xDEADBEEF
        ts = float(time.time())
        packet = struct.pack(
            "<IffffIII",
            magic,
            ts,
            bin_fill_pct,
            temperature_c,
            humidity_pct,
            gas_adc,
            moisture_adc,
            alert_flag,
        )
        self.mem[0:32] = packet

    def read_sensor_snapshot(self) -> Dict:
        """Read 32-byte telemetry record from BRAM offset 0x00"""
        packet = self.mem[0:32]
        magic, ts, bin_fill, temp, hum, gas, moist, alert = struct.unpack(
            "<IffffIII", packet
        )
        if magic != 0xDEADBEEF:
            return {"valid": False}
        return {
            "valid": True,
            "timestamp": ts,
            "bin_fill_pct": bin_fill,
            "temperature_c": temp,
            "humidity_pct": hum,
            "gas_adc": gas,
            "moisture_adc": moist,
            "alert_flag": alert,
        }

    def close(self):
        if self.fd and self.mem and self.is_hardware_active:
            self.mem.close()
            os.close(self.fd)


if __name__ == "__main__":
    bram = DirectBRAMInterface()
    print(f"BRAM Interface Initialized. Hardware Active: {bram.is_hardware_active}")
    bram.write_sensor_snapshot(74.5, 28.2, 55.0, 420, 18500, 0)
    data = bram.read_sensor_snapshot()
    print("Readback from BRAM Buffer:", data)
    bram.close()

